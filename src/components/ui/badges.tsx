export function DataSourceBadge({ source }: { source: DataSourceType }) {
  if (source === "Telemetry") {
    return (
      <span
        title="Recorded from PLC / sensor telemetry stream"
        className="inline-flex items-center gap-1 px-2 py-0.5 rounded text-[11px] font-medium bg-emerald-500/10 text-emerald-700 dark:text-emerald-300 border border-emerald-500/25"
      >
        <Activity className="w-3 h-3" />
        Telemetry
      </span>
    );
  }
  if (source === "Simulation") {
    return (
      <span
        title="Generated by deterministic Digital Twin software model"
        className="inline-flex items-center gap-1 px-2 py-0.5 rounded text-[11px] font-medium bg-indigo-500/10 text-indigo-700 dark:text-indigo-300 border border-indigo-500/25"
      >
        <Cpu className="w-3 h-3" />
        Simulated
      </span>
    );
  }
  return (
    <span
      title="Manually entered by authenticated shop-floor personnel"
      className="inline-flex items-center gap-1 px-2 py-0.5 rounded text-[11px] font-medium bg-slate-500/10 text-slate-700 dark:text-slate-300 border border-slate-500/25"
    >
      <PenTool className="w-3 h-3" />
      Manual Entry
    </span>
  );
}


export function MachineStatusBadge({ status }: { status: MachineStatus }) {
  const styles: Record<MachineStatus, string> = {
    Running:
      "bg-emerald-500/15 text-emerald-700 dark:text-emerald-300 border-emerald-500/30",
    Idle: "bg-slate-500/15 text-slate-700 dark:text-slate-300 border-slate-500/30",
    Warning:
      "bg-amber-500/15 text-amber-700 dark:text-amber-300 border-amber-500/30",
    Error: "bg-rose-500/15 text-rose-700 dark:text-rose-300 border-rose-500/30",
    Maintenance:
      "bg-blue-500/15 text-blue-700 dark:text-blue-300 border-blue-500/30",
  };

  const dotColors: Record<MachineStatus, string> = {
    Running: "bg-emerald-500",
    Idle: "bg-slate-400",
    Warning: "bg-amber-500",
    Error: "bg-rose-500",
    Maintenance: "bg-blue-500",
  };

  return (
    <span
      className={`inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded text-xs font-medium border ${styles[status]}`}
    >
      <span className={`w-1.5 h-1.5 rounded-full ${dotColors[status]}`} />
      {status}
    </span>
  );
}

